export function applySupportLanguage(document, value) {
  const language = normalizeLanguage(value);
  const common = translations[language];
  const copy = { ...common, ...supportTranslations[language] };
  document.documentElement.lang = common.htmlLanguage;
  document.title = `${copy.supportPageLabel} · SERIAL`;
  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = copy[element.dataset.i18n];
  }
  for (const element of document.querySelectorAll('[data-i18n-aria]')) {
    element.setAttribute('aria-label', copy[element.dataset.i18nAria]);
  }
  for (const button of document.querySelectorAll('[data-language-choice]')) {
    button.setAttribute('aria-pressed', String(button.dataset.languageChoice === language));
  }
  for (const element of document.querySelectorAll('meta[name="description"], meta[property="og:description"], meta[name="twitter:description"]')) element.content = copy.supportIntro;
  for (const element of document.querySelectorAll('meta[property="og:title"], meta[name="twitter:title"]')) element.content = document.title;
  document.querySelector('meta[property="og:locale"]').content = common.locale;
  return language;
}
